"""Build a repository-level corpus of permissively licensed C-family code from GitHub.

Three steps (run all with `all`, or one at a time):

    python scripts/build_code_corpus.py search     # find repositories   -> data/code-raw/repos.json
    python scripts/build_code_corpus.py download   # fetch tarballs      -> data/code-raw/tarballs/
    python scripts/build_code_corpus.py extract    # filter + split      -> data/code-raw/{train,val,test}.jsonl
    python scripts/build_code_corpus.py all

Each output line of {split}.jsonl is one repository:
    {"repo", "url", "license", "language", "stars", "created", "files": [{"path", "lang", "text"}]}
Files are in dependency order: build files first, then headers before the files that
#include them, then everything else by path.

What is kept
  - repositories: not forks, license in PERMISSIVE (from GitHub's license detection),
    under --max-repo-mb, found by searching each language in LANGUAGES
  - files: extensions/names in FILE_TYPES, at most 512 KB, valid UTF-8, not minified or
    generated, not under vendored/third-party/build directories
  - exact duplicate files are removed across the whole corpus; a file that occurs in a
    val/test repository is removed from every train repository (no leakage)
Splits are by repository (hash of the name): 90% train, 5% val, 5% test.

Network: GitHub's search API (unauthenticated: 10 searches/minute; set GITHUB_TOKEN for
more) and codeload.github.com for tarballs. A license list for attribution is written to
data/code-raw/LICENSES.tsv.
"""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import os
import re
import sys
import tarfile
import time
import urllib.error
import urllib.parse
import urllib.request
from collections import Counter, defaultdict
from pathlib import Path, PurePosixPath

# GitHub language name -> number of repositories to collect
LANGUAGES = {"C": 160, "C++": 160, "C#": 100, "Objective-C": 40, "Cuda": 40}
PERMISSIVE = ["mit", "apache-2.0", "bsd-3-clause", "bsd-2-clause", "isc", "zlib", "bsl-1.0", "unlicense"]

EXT_LANG = {
    ".c": "c", ".h": "c-header",
    ".cc": "cpp", ".cpp": "cpp", ".cxx": "cpp", ".c++": "cpp",
    ".hh": "cpp-header", ".hpp": "cpp-header", ".hxx": "cpp-header", ".h++": "cpp-header",
    ".ipp": "cpp-header", ".tpp": "cpp-header", ".inl": "cpp-header",
    ".cu": "cuda", ".cuh": "cuda-header",
    ".m": "objc", ".mm": "objcpp",
    ".cs": "csharp", ".csproj": "csproj",
    ".s": "asm", ".asm": "asm",
    ".cmake": "cmake", ".mk": "make", ".bzl": "bazel", ".ld": "linker", ".sh": "shell",
}
NAME_LANG = {
    "CMakeLists.txt": "cmake", "Makefile": "make", "makefile": "make", "GNUmakefile": "make",
    "Makefile.am": "autotools", "configure.ac": "autotools", "meson.build": "meson",
    "meson_options.txt": "meson", "BUILD": "bazel", "BUILD.bazel": "bazel", "WORKSPACE": "bazel",
}
BUILD_LANGS = {"cmake", "make", "autotools", "meson", "bazel", "csproj"}
HEADER_LANGS = {"c-header", "cpp-header", "cuda-header"}
SKIP_DIRS = {"third_party", "thirdparty", "3rdparty", "third-party", "vendor", "vendors", "external",
             "extern", "deps", "node_modules", "build", "out", "dist", ".git", "bin", "obj", "packages"}
MAX_FILE_BYTES = 512 * 1024
GENERATED = re.compile(r"(auto-?generated|generated by|do not edit)", re.IGNORECASE)
INCLUDE = re.compile(r'^\s*#\s*(?:include|import)\s*"([^"]+)"', re.MULTILINE)

API = "https://api.github.com/search/repositories"


# ---------------------------------------------------------------- search

def _get_json(url: str) -> dict:
    headers = {"Accept": "application/vnd.github+json", "User-Agent": "code-corpus-builder"}
    if os.environ.get("GITHUB_TOKEN"):
        headers["Authorization"] = f"Bearer {os.environ['GITHUB_TOKEN']}"
    for attempt in range(5):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=60) as r:
                return json.load(r)
        except urllib.error.HTTPError as e:
            if e.code in (403, 429):  # rate limited: wait and retry
                wait = 65 * (attempt + 1)
                print(f"  rate limited, waiting {wait}s", flush=True)
                time.sleep(wait)
                continue
            raise
    raise RuntimeError(f"giving up on {url}")


def search_query(language: str, license: str, min_stars: int, max_kb: int, created_after: str | None) -> str:
    q = f'language:"{language}" license:{license} stars:>={min_stars} size:<={max_kb} fork:false archived:false'
    if created_after:
        q += f" created:>{created_after}"
    return q


def search(args):
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    delay = 2.5 if os.environ.get("GITHUB_TOKEN") else 7.0  # stay under the search rate limit
    found: dict[str, dict] = {}
    for language, quota in LANGUAGES.items():
        quota = max(1, int(quota * args.scale))
        got = 0
        for lic in PERMISSIVE:
            if got >= quota:
                break
            page = 1
            while got < quota and page <= 3:
                q = search_query(language, lic, args.min_stars, int(args.max_repo_mb * 1024), args.created_after)
                url = API + "?" + urllib.parse.urlencode({"q": q, "sort": "stars", "order": "desc",
                                                          "per_page": 100, "page": page})
                items = _get_json(url).get("items", [])
                time.sleep(delay)
                for it in items:
                    if got >= quota:
                        break
                    if it["full_name"] in found or not it.get("license"):
                        continue
                    found[it["full_name"]] = {
                        "repo": it["full_name"], "url": it["html_url"], "language": language,
                        "license": it["license"]["spdx_id"], "stars": it["stargazers_count"],
                        "size_kb": it["size"], "branch": it["default_branch"], "created": it["created_at"],
                    }
                    got += 1
                if len(items) < 100:
                    break
                page += 1
        print(f"{language}: {got} repositories", flush=True)
    (out / "repos.json").write_text(json.dumps(list(found.values()), indent=1))
    print(f"wrote {len(found)} repositories to {out / 'repos.json'}")


# ---------------------------------------------------------------- download

def tarball_name(repo: str) -> str:
    return repo.replace("/", "__") + ".tar.gz"


def download(args):
    out = Path(args.out)
    repos = json.loads((out / "repos.json").read_text())
    tdir = out / "tarballs"
    tdir.mkdir(exist_ok=True)
    for i, r in enumerate(repos):
        dest = tdir / tarball_name(r["repo"])
        if dest.exists():
            continue
        url = f"https://codeload.github.com/{r['repo']}/tar.gz/refs/heads/{urllib.parse.quote(r['branch'])}"
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "code-corpus-builder"}),
                                        timeout=300) as resp:
                data = resp.read()
            tmp = dest.with_suffix(".part")
            tmp.write_bytes(data)
            tmp.rename(dest)
        except Exception as e:  # a missing or huge repo is not fatal
            print(f"  skip {r['repo']}: {type(e).__name__}: {e}", flush=True)
        if (i + 1) % 25 == 0:
            print(f"downloaded {i + 1}/{len(repos)}", flush=True)
    print("download done")


# ---------------------------------------------------------------- extract

def file_lang(path: str) -> str | None:
    p = PurePosixPath(path)
    if p.name in NAME_LANG:
        return NAME_LANG[p.name]
    if p.suffix == ".S":
        return "asm"
    return EXT_LANG.get(p.suffix.lower())


def keep_path(path: str) -> bool:
    return not any(part.lower() in SKIP_DIRS for part in PurePosixPath(path).parts[:-1])


def clean_text(raw: bytes) -> str | None:
    if len(raw) > MAX_FILE_BYTES or b"\x00" in raw:
        return None
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError:
        return None
    lines = text.splitlines()
    if not lines or not text.strip():
        return None
    if max(len(line) for line in lines) > 1000 or len(text) / len(lines) > 200:
        return None  # minified or data blob
    if GENERATED.search("\n".join(lines[:10])):
        return None
    return text


def split_of(repo: str) -> str:
    h = int(hashlib.sha1(repo.encode()).hexdigest(), 16) % 100
    return "train" if h < 90 else "val" if h < 95 else "test"


def dependency_order(files: list[dict]) -> list[dict]:
    """Build files first, then a topological order of local #include/#import edges
    (an included file comes before its includers), ties broken by kind and path."""
    def rank(f):
        return (0 if f["lang"] in BUILD_LANGS else 1 if f["lang"] in HEADER_LANGS else 2, f["path"])

    by_name = defaultdict(list)
    for i, f in enumerate(files):
        by_name[PurePosixPath(f["path"]).name].append(i)
    deps = defaultdict(set)  # i -> files that i includes
    for i, f in enumerate(files):
        for inc in INCLUDE.findall(f["text"]):
            for j in by_name.get(PurePosixPath(inc).name, []):
                if j != i:
                    deps[i].add(j)
    order, state = [], {}

    def visit(i):  # depth-first; cycles are broken by ignoring back edges
        if state.get(i) is not None:
            return
        state[i] = "visiting"
        for j in sorted(deps[i], key=lambda j: rank(files[j])):
            visit(j)
        state[i] = "done"
        order.append(i)

    for i in sorted(range(len(files)), key=lambda i: rank(files[i])):
        visit(i)
    return [files[i] for i in order]


def read_repo(tar_path: Path) -> list[dict]:
    files = []
    with tarfile.open(tar_path, "r:gz") as tf:
        for m in tf:
            if not m.isfile() or m.size > MAX_FILE_BYTES:
                continue
            path = m.name.split("/", 1)[1] if "/" in m.name else m.name  # drop "<repo>-<branch>/"
            lang = file_lang(path)
            if lang is None or not keep_path(path):
                continue
            fobj = tf.extractfile(m)
            text = clean_text(fobj.read()) if fobj else None
            if text is not None:
                files.append({"path": path, "lang": lang, "text": text})
    return files


def extract(args):
    out = Path(args.out)
    repos = json.loads((out / "repos.json").read_text())
    loaded = []
    for r in repos:
        tp = out / "tarballs" / tarball_name(r["repo"])
        if not tp.exists():
            continue
        try:
            files = read_repo(tp)
        except (tarfile.TarError, OSError, EOFError) as e:
            print(f"  skip {r['repo']}: {e}", flush=True)
            continue
        if files:
            loaded.append((r, split_of(r["repo"]), files))

    # Exact dedup: val/test files claim their hashes first, so train never contains them.
    def digest(text):
        return hashlib.sha1(text.encode()).hexdigest()

    seen = set()
    order = {"test": 0, "val": 1, "train": 2}
    loaded.sort(key=lambda x: (order[x[1]], x[0]["repo"]))
    stats = Counter()
    writers = {s: open(out / f"{s}.jsonl", "w", encoding="utf-8") for s in order}
    lic = open(out / "LICENSES.tsv", "w", encoding="utf-8")
    lic.write("repo\tlicense\turl\tsplit\n")
    for r, split, files in loaded:
        kept = []
        for f in files:
            d = digest(f["text"])
            if d in seen:
                stats["duplicate files removed"] += 1
                continue
            seen.add(d)
            kept.append(f)
        if not kept:
            continue
        kept = dependency_order(kept)
        rec = {k: r[k] for k in ("repo", "url", "license", "language", "stars", "created")}
        rec["files"] = kept
        writers[split].write(json.dumps(rec, ensure_ascii=False) + "\n")
        lic.write(f"{r['repo']}\t{r['license']}\t{r['url']}\t{split}\n")
        stats[f"{split} repos"] += 1
        for f in kept:
            n = len(f["text"].encode("utf-8"))
            stats[f"{split} bytes"] += n
            stats[f"bytes {f['lang']}"] += n
    for w in writers.values():
        w.close()
    lic.close()
    summary = dict(sorted(stats.items()))
    (out / "summary.json").write_text(json.dumps(summary, indent=2))
    print(json.dumps(summary, indent=2))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("step", choices=["search", "download", "extract", "all"])
    ap.add_argument("--out", default="data/code-raw")
    ap.add_argument("--scale", type=float, default=1.0, help="multiply the per-language repository counts")
    ap.add_argument("--min-stars", type=int, default=20)
    ap.add_argument("--max-repo-mb", type=float, default=50)
    ap.add_argument("--created-after", help="only repositories created after this date (YYYY-MM-DD)")
    args = ap.parse_args()
    for step in (["search", "download", "extract"] if args.step == "all" else [args.step]):
        {"search": search, "download": download, "extract": extract}[step](args)


if __name__ == "__main__":
    sys.exit(main())
